#!/usr/bin/env python3
"""
scripts/run_comprehensive_evaluation.py

Comprehensive evaluation script — Step 3 & 4 of the batch pipeline.

1. Loads output/quality_iteration_report.json (generated by run_cag_evaluation.py)
2. Scans output/cag/ directories for generated DOCX/PDF runs
3. For each doc type, finds the best-scoring run (highest combined Tier1+Tier2 score)
4. Runs evaluate_cag_document() on each generated document
5. Writes output/quality_baselines.json  — best run per doc type with issues
6. Writes output/evaluation_results.json — summary of the latest comprehensive run

Usage:
    python -W ignore scripts/run_comprehensive_evaluation.py
"""
