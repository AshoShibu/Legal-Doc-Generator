DOC_TYPES = list(TEMPLATE_SLOTS.keys())

# ---------------------------------------------------------------------------
# Stub LLM (same as run_cag_evaluation.py — prevents real API calls)
# ---------------------------------------------------------------------------

def _stub_llm(*args, **kwargs) -> str:
    return "STUB LLM RESPONSE — evaluation only, no generation needed."


# ---------------------------------------------------------------------------
# Mock document dataclass (matches evaluator interface)
# ---------------------------------------------------------------------------

from dataclasses import dataclass, field as dc_field

@dataclass
class _MockDoc:
    content: str
    body: str
    citations: list
    ungrounded_clauses: list
    run_id: str = "eval"
    doc_type: str = "unknown"
    pipeline_variant: str = "CAG"


# ---------------------------------------------------------------------------
# Scan output/cag/ for generated runs
# ---------------------------------------------------------------------------

def scan_cag_runs() -> dict[str, list[dict]]:
    """
    Scan output/cag/{doc_type}/{run_id}/ directories.
    Returns dict mapping doc_type -> list of run info dicts.
    """
    runs: dict[str, list[dict]] = {dt: [] for dt in DOC_TYPES}

    if not CAG_ROOT.exists():
        print(f"  WARNING: {CAG_ROOT} does not exist — no runs to scan.")
        return runs

    for doc_type in DOC_TYPES:
        doc_dir = CAG_ROOT / doc_type
        if not doc_dir.exists():
            continue
        for run_dir in sorted(doc_dir.iterdir()):
            if not run_dir.is_dir():
                continue
            run_id = run_dir.name
            # Find DOCX and PDF files
            docx_files = list(run_dir.glob("*.docx"))
            pdf_files = list(run_dir.glob("*.pdf"))
            runs[doc_type].append({
                "run_id": run_id,
                "doc_type": doc_type,
                "run_dir": run_dir,
                "docx_path": docx_files[0] if docx_files else None,
                "pdf_path": pdf_files[0] if pdf_files else None,
            })

    return runs


# ---------------------------------------------------------------------------
# Evaluate a single run directory
# ---------------------------------------------------------------------------

def evaluate_run(run_info: dict) -> dict | None:
    """
    Evaluate a generated document run using Tier 1 + Tier 2 metrics.
    Reads the DOCX content (or falls back to a stub) and runs evaluate_cag_document().
    Returns a flat metrics dict, or None on failure.
    """
    from src.evaluation.evaluator import evaluate_cag_document

    doc_type = run_info["doc_type"]
    run_id = run_info["run_id"]
    slots = TEMPLATE_SLOTS.get(doc_type, [])

    # Try to read document content from DOCX
    body_text = ""
    docx_path = run_info.get("docx_path")
    if docx_path and Path(docx_path).exists():
        try:
            from docx import Document as DocxDocument
            doc = DocxDocument(str(docx_path))
            body_text = "\n".join(p.text for p in doc.paragraphs if p.text.strip())
        except Exception as e:
            print(f"    WARNING: Could not read DOCX {docx_path.name}: {e}")

    if not body_text:
        # Fallback: try to load via CAG engine with stub LLM
        try:
            from src.cag.engine import load_cache, generate_draft
            fact_pattern = {"intake": {}, "ocr_fields": {}}
            with patch("src.cag.engine._call_ollama", return_value=_stub_llm()):
                with patch("src.cag.engine._call_groq", return_value=_stub_llm()):
                    cache = load_cache(doc_type, "groq_llama3_8b")
                    draft = generate_draft(fact_pattern, cache, doc_type, template_slots=slots)
            body_text = draft.content
        except Exception as e:
            print(f"    WARNING: Could not generate fallback draft for {doc_type}/{run_id}: {e}")
            return None

    # Build a mock doc object
    # Parse citations from body (simple heuristic: [Act, Year] patterns)
    import re
    citation_pattern = re.compile(r"\[([A-Za-z][^\]]*?,\s*\d{4})\]", re.IGNORECASE)
    ungrounded_pattern = re.compile(
        r"\[(UNGROUNDED|GROQ_UNAVAILABLE|OLLAMA_UNAVAILABLE|AGENT_TIMEOUT)[^\]]*\]",
        re.IGNORECASE,
    )
    citations = citation_pattern.findall(body_text)
    ungrounded = ungrounded_pattern.findall(body_text)

    mock_doc = _MockDoc(
        content=body_text,
        body=body_text,
        citations=citations,
        ungrounded_clauses=ungrounded,
        run_id=run_id,
        doc_type=doc_type,
        pipeline_variant="CAG",
    )

    # Use a minimal fact pattern (no intake data available for existing runs)
    fact_pattern = {"intake": {}, "ocr_fields": {}}

    t0 = time.monotonic()
    try:
        result = evaluate_cag_document(
            doc=mock_doc,
            fact_pattern=fact_pattern,
            template_slots=slots,
            latency_seconds=0.0,
        )
    except Exception as e:
        print(f"    ERROR evaluating {doc_type}/{run_id}: {e}")
        return None

    summary = result.summary()
    # Combined score: sum of key Tier1+Tier2 metrics
    combined = (
        summary.get("cache_hit_rate", 0)
        + summary.get("slot_fill_rate", 0)
        + summary.get("fact_fidelity_score", 0)
        + summary.get("section_completeness", 0)
        + summary.get("citation_format_compliance", 0)
        + summary.get("jurisdictional_accuracy", 0)
    )
    summary["combined_score"] = round(combined, 4)
    summary["run_dir"] = str(run_info["run_dir"])
    summary["docx_path"] = str(docx_path) if docx_path else None
    summary["pdf_path"] = str(run_info.get("pdf_path")) if run_info.get("pdf_path") else None
    return summary


# ---------------------------------------------------------------------------
# Build issues list for a metrics dict
# ---------------------------------------------------------------------------

def build_issues(metrics: dict) -> list[str]:
    """Return list of human-readable issue strings for metrics below threshold."""
    issues = []
    fix_hints = {
        "cache_hit_rate": "increase cache coverage or add more grounded citations",
        "fact_fidelity_score": "improve intake field injection into prompt template",
        "section_completeness": "ensure all section headings are present in template",
        "citation_format_compliance": "fix citation format to [Act, Year] Section X, Court, Year",
        "jurisdictional_accuracy": "replace non-Maharashtra citations with valid acts",
        "slot_fill_rate": "fill all template slots with substantive content (>50 tokens)",
    }
    for metric, threshold in THRESHOLDS.items():
        val = metrics.get(metric)
        if val is not None and val < threshold:
            hint = fix_hints.get(metric, "review and fix")
            issues.append(
                f"{metric} {val:.4f} below threshold {threshold} -> {hint}"
            )
    return issues


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    print("=" * 70)
    print("  Comprehensive CAG Evaluation")
    print("=" * 70)

    # ---- Load quality_iteration_report.json ----
    print(f"\nLoading {QUALITY_REPORT_PATH.relative_to(ROOT)} ...", end=" ")
    if not QUALITY_REPORT_PATH.exists():
        print("NOT FOUND — run scripts/run_cag_evaluation.py first.")
        sys.exit(1)
    quality_report = json.loads(QUALITY_REPORT_PATH.read_text(encoding="utf-8"))
    print(f"OK ({quality_report.get('evaluated_count', '?')} queries evaluated)")

    # ---- Scan output/cag/ for generated runs ----
    print(f"\nScanning {CAG_ROOT.relative_to(ROOT)} for generated runs ...")
    all_runs = scan_cag_runs()
    total_runs = sum(len(v) for v in all_runs.values())
    print(f"  Found {total_runs} run directories across {len(DOC_TYPES)} doc types")
    for dt, runs in all_runs.items():
        print(f"    {dt:<25s}: {len(runs)} run(s)")

    # ---- Evaluate each run ----
    print("\nEvaluating runs ...")
    evaluated: dict[str, list[dict]] = {dt: [] for dt in DOC_TYPES}

    for doc_type in DOC_TYPES:
        runs = all_runs[doc_type]
        if not runs:
            print(f"  {doc_type:<25s}: no runs found, skipping")
            continue
        for run_info in runs:
            run_id_short = run_info["run_id"][:8]
            print(f"  {doc_type:<25s} [{run_id_short}] ...", end=" ", flush=True)
            metrics = evaluate_run(run_info)
            if metrics:
                evaluated[doc_type].append(metrics)
                sc = metrics.get("section_completeness", 0)
                ff = metrics.get("fact_fidelity_score", 0)
                cs = metrics.get("combined_score", 0)
                print(f"SecComp={sc:.2f}  FactFid={ff:.2f}  Combined={cs:.2f}")
            else:
                print("FAILED")

    # ---- Find best run per doc type ----
    print("\nSelecting best run per doc type ...")
    best_runs: dict[str, dict] = {}
    for doc_type in DOC_TYPES:
        runs = evaluated[doc_type]
        if not runs:
            print(f"  {doc_type:<25s}: no evaluated runs")
            continue
        best = max(runs, key=lambda r: r.get("combined_score", 0))
        best_runs[doc_type] = best
        print(f"  {doc_type:<25s}: best run_id={best['run_id'][:8]}  combined={best.get('combined_score', 0):.4f}")

    # ---- Also incorporate per_query_rows from quality_iteration_report ----
    # Use the quality report data to supplement/override where we have richer metrics
    per_query_rows = quality_report.get("per_query_rows", [])
    per_type_agg = quality_report.get("per_doc_type_aggregates", {})

    # Build a lookup: doc_type -> best query row from quality report
    best_query_by_type: dict[str, dict] = {}
    for row in per_query_rows:
        dt = row.get("doc_type")
        if not dt:
            continue
        combined = (
            row.get("cache_hit_rate", 0)
            + row.get("slot_fill_rate", 0)
            + row.get("fact_fidelity_score", 0)
            + row.get("section_completeness", 0)
            + row.get("citation_format_compliance", 0)
            + row.get("jurisdictional_accuracy", 0)
        )
        row["_combined"] = combined
        if dt not in best_query_by_type or combined > best_query_by_type[dt]["_combined"]:
            best_query_by_type[dt] = row

    # ---- Build quality_baselines.json ----
    print("\nBuilding quality_baselines.json ...")
    baselines: dict[str, dict] = {}

    for doc_type in DOC_TYPES:
        # Prefer metrics from the evaluated DOCX runs; fall back to quality report
        if doc_type in best_runs:
            m = best_runs[doc_type]
            run_id = m["run_id"]
        elif doc_type in best_query_by_type:
            m = best_query_by_type[doc_type]
            run_id = m.get("run_id", doc_type)
        else:
            print(f"  WARNING: no data for {doc_type}, skipping baseline")
            continue

        issues = build_issues(m)
        baselines[doc_type] = {
            "run_id": run_id,
            "doc_type": doc_type,
            "pipeline_variant": m.get("pipeline_variant", "CAG"),
            "cache_hit_rate": m.get("cache_hit_rate", 0.0),
            "slot_fill_rate": m.get("slot_fill_rate", 0.0),
            "fact_fidelity_score": m.get("fact_fidelity_score", 0.0),
            "latency_seconds": m.get("latency_seconds", 0.0),
            "grounded_citations": m.get("grounded_citations", 0),
            "ungrounded_citations": m.get("ungrounded_citations", 0),
            "section_completeness": m.get("section_completeness", 0.0),
            "citation_format_compliance": m.get("citation_format_compliance", 0.0),
            "jurisdictional_accuracy": m.get("jurisdictional_accuracy", 0.0),
            "combined_score": m.get("combined_score", m.get("_combined", 0.0)),
            "issues": issues,
        }

    baselines_out = {
        "generated_at": datetime.utcnow().isoformat() + "Z",
        "thresholds": THRESHOLDS,
        "baselines": baselines,
    }

    baselines_path = OUTPUT_ROOT / "quality_baselines.json"
    baselines_path.write_text(
        json.dumps(baselines_out, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    print(f"  Written -> {baselines_path.relative_to(ROOT)}")

    # ---- Build evaluation_results.json ----
    print("\nBuilding evaluation_results.json ...")

    threshold_check = quality_report.get("threshold_check", {})
    overall_pass = threshold_check.get("overall_pass", False)
    threshold_failures = threshold_check.get("failures", [])

    per_doc_type_out: dict[str, dict] = {}
    for doc_type in DOC_TYPES:
        agg = per_type_agg.get(doc_type, {})
        best_q = best_query_by_type.get(doc_type, {})
        best_run = best_runs.get(doc_type, {})

        combined_score = best_q.get("_combined", 0.0)
        if best_run:
            combined_score = max(combined_score, best_run.get("combined_score", 0.0))

        per_doc_type_out[doc_type] = {
            "best_query_id": best_q.get("query_id", best_q.get("run_id", doc_type)),
            "best_run_id": best_run.get("run_id", best_q.get("run_id", "")),
            "combined_score": round(combined_score, 4),
            "cache_hit_rate_mean": agg.get("cache_hit_rate_mean"),
            "fact_fidelity_score_mean": agg.get("fact_fidelity_score_mean"),
            "section_completeness_mean": agg.get("section_completeness_mean"),
            "citation_format_compliance_mean": agg.get("citation_format_compliance_mean"),
            "jurisdictional_accuracy_mean": agg.get("jurisdictional_accuracy_mean"),
            "slot_fill_rate_mean": agg.get("slot_fill_rate_mean"),
            "latency_seconds_mean": agg.get("latency_seconds_mean"),
        }

    eval_results = {
        "generated_at": datetime.utcnow().isoformat() + "Z",
        "total_runs": total_runs,
        "doc_types_evaluated": len([dt for dt in DOC_TYPES if dt in best_runs or dt in best_query_by_type]),
        "overall_pass": overall_pass,
        "per_doc_type": per_doc_type_out,
        "threshold_failures": threshold_failures,
        "source": str(QUALITY_REPORT_PATH.relative_to(ROOT)),
    }

    eval_results_path = OUTPUT_ROOT / "evaluation_results.json"
    eval_results_path.write_text(
        json.dumps(eval_results, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    print(f"  Written -> {eval_results_path.relative_to(ROOT)}")

    # ---- Summary ----
    print()
    print("=" * 70)
    print("  COMPREHENSIVE EVALUATION COMPLETE")
    print("=" * 70)
    print(f"  Total runs scanned   : {total_runs}")
    print(f"  Doc types evaluated  : {len(best_runs)}/7")
    print(f"  Overall pass         : {'YES' if overall_pass else 'NO'}")
    print(f"  Threshold failures   : {len(threshold_failures)}")
    print()
    print("  Output files updated:")
    print(f"    {QUALITY_REPORT_PATH.relative_to(ROOT)}")
    print(f"    {(OUTPUT_ROOT / 'cag_evaluation_report.csv').relative_to(ROOT)}")
    print(f"    {baselines_path.relative_to(ROOT)}")
    print(f"    {eval_results_path.relative_to(ROOT)}")
    print("=" * 70)


if __name__ == "__main__":
    main()
